package domain

import (
	"fmt"
	"strings"
	"time"
)

// Platform identifies a supported social media publishing target.
type Platform string

const (
	// PlatformLinkedIn represents LinkedIn posts published via Buffer.
	PlatformLinkedIn Platform = "linkedin"
	// PlatformYouTube represents YouTube Shorts/videos published via YouTube Data API v3.
	PlatformYouTube Platform = "youtube"
	// PlatformX represents X (Twitter) posts published via Buffer.
	PlatformX Platform = "x"
	// PlatformTikTok represents TikTok short videos published via Buffer.
	PlatformTikTok Platform = "tiktok"
)

// AllPlatforms returns the canonical list of supported social platforms in deterministic order.
func AllPlatforms() []Platform {
	return []Platform{
		PlatformLinkedIn,
		PlatformYouTube,
		PlatformX,
		PlatformTikTok,
	}
}

// ParsePlatform validates and normalizes a raw platform identifier string.
func ParsePlatform(rawPlatform string) (Platform, error) {
	normalized := Platform(strings.ToLower(strings.TrimSpace(rawPlatform)))
	switch normalized {
	case PlatformLinkedIn, PlatformYouTube, PlatformX, PlatformTikTok:
		return normalized, nil
	default:
		return "", fmt.Errorf("%w: unsupported platform %q", ErrValidationFailed, rawPlatform)
	}
}

// DraftStatus tracks a ContentDraft through generation, critique, human review, and publishing.
type DraftStatus string

const (
	// StatusDraft indicates initial content generated by a platform subagent.
	StatusDraft DraftStatus = "DRAFT"
	// StatusCritiqued indicates content reviewed and refined by the Content Critic Agent.
	StatusCritiqued DraftStatus = "CRITIQUED"
	// StatusPendingReview indicates content awaiting human approval in Discord or Telegram.
	StatusPendingReview DraftStatus = "PENDING_REVIEW"
	// StatusApproved indicates content approved by a human reviewer and queued for publishing.
	StatusApproved DraftStatus = "APPROVED"
	// StatusRejected indicates content rejected by a human reviewer (no publishing occurs).
	StatusRejected DraftStatus = "REJECTED"
	// StatusPublished indicates content successfully published to the target social platform.
	StatusPublished DraftStatus = "PUBLISHED"
	// StatusFailed indicates a publishing error after human approval.
	StatusFailed DraftStatus = "FAILED"
)

// IsTerminal reports whether the draft has reached a final human decision or publishing outcome.
func (status DraftStatus) IsTerminal() bool {
	return status == StatusRejected || status == StatusPublished || status == StatusFailed
}

// MediaType describes the generated binary asset attached to a social post.
type MediaType string

const (
	// MediaNone indicates a text-only post with no attached media.
	MediaNone MediaType = "NONE"
	// MediaImage indicates a generated image asset (e.g., PNG/JPEG for LinkedIn or X).
	MediaImage MediaType = "IMAGE"
	// MediaVideo indicates a generated video asset (e.g., MP4 for YouTube or TikTok).
	MediaVideo MediaType = "VIDEO"
)

// CommitEvent captures immutable metadata and diff context from a git commit or push trigger.
type CommitEvent struct {
	RepoName       string    `json:"repo_name"`
	Branch         string    `json:"branch"`
	CommitSHA      string    `json:"commit_sha"`
	Author         string    `json:"author"`
	Message        string    `json:"message"`
	Timestamp      time.Time `json:"timestamp"`
	ChangedFiles   []string  `json:"changed_files"`
	DiffPatch      string    `json:"diff_patch"`
	IdempotencyKey string    `json:"idempotency_key"`
}

// Validate enforces required commit fields and derives a deterministic idempotency key when omitted.
func (event *CommitEvent) Validate() error {
	if strings.TrimSpace(event.CommitSHA) == "" {
		return fmt.Errorf("%w: commit_sha is required", ErrValidationFailed)
	}
	if strings.TrimSpace(event.RepoName) == "" {
		event.RepoName = "local-repository"
	}
	if strings.TrimSpace(event.Branch) == "" {
		event.Branch = "main"
	}
	if strings.TrimSpace(event.Message) == "" {
		return fmt.Errorf("%w: commit message is required", ErrValidationFailed)
	}
	if strings.TrimSpace(event.IdempotencyKey) == "" {
		// Normalize idempotency per repository and commit SHA so duplicate webhook deliveries do not re-trigger generation.
		event.IdempotencyKey = fmt.Sprintf("%s:%s", strings.TrimSpace(event.RepoName), strings.TrimSpace(event.CommitSHA))
	}
	if event.Timestamp.IsZero() {
		event.Timestamp = time.Now().UTC()
	}
	return nil
}

// MediaAsset holds references to a generated image or video stored in object/local storage.
type MediaAsset struct {
	ID        string    `json:"id"`
	MediaType MediaType `json:"media_type"`
	MimeType  string    `json:"mime_type"`
	LocalPath string    `json:"local_path,omitempty"`
	PublicURL string    `json:"public_url,omitempty"`
	SizeBytes int64     `json:"size_bytes"`
}

// ContentDraft represents a single platform-specific post generated from a CommitEvent.
type ContentDraft struct {
	ID             string      `json:"id"`
	BatchID        string      `json:"batch_id"`
	CommitSHA      string      `json:"commit_sha"`
	Platform       Platform    `json:"platform"`
	Title          string      `json:"title"`
	BodyText       string      `json:"body_text"`
	Tags           []string    `json:"tags"`
	MediaAsset     *MediaAsset `json:"media_asset,omitempty"`
	Status         DraftStatus `json:"status"`
	CriticNotes    string      `json:"critic_notes,omitempty"`
	ExternalPostID string      `json:"external_post_id,omitempty"`
	FailureReason  string      `json:"failure_reason,omitempty"`
	Version        int         `json:"version"`
	CreatedAt      time.Time   `json:"created_at"`
	UpdatedAt      time.Time   `json:"updated_at"`
}

// ApplyCritique updates draft copy and transitions the draft from DRAFT/CRITIQUED to CRITIQUED.
func (draft *ContentDraft) ApplyCritique(title, bodyText, criticNotes string, tags []string) error {
	if draft.Status != StatusDraft && draft.Status != StatusCritiqued {
		return fmt.Errorf("%w: cannot critique draft in status %s", ErrInvalidStateTransition, draft.Status)
	}
	if strings.TrimSpace(bodyText) == "" {
		return fmt.Errorf("%w: critiqued body_text cannot be empty", ErrValidationFailed)
	}
	draft.Title = strings.TrimSpace(title)
	draft.BodyText = strings.TrimSpace(bodyText)
	draft.CriticNotes = strings.TrimSpace(criticNotes)
	if tags != nil {
		draft.Tags = append([]string(nil), tags...)
	}
	draft.Status = StatusCritiqued
	draft.Version++
	draft.UpdatedAt = time.Now().UTC()
	return nil
}

// MarkPendingReview transitions a drafted or critiqued post into human review.
func (draft *ContentDraft) MarkPendingReview() error {
	if draft.Status != StatusDraft && draft.Status != StatusCritiqued && draft.Status != StatusPendingReview {
		return fmt.Errorf("%w: cannot move draft from %s to %s", ErrInvalidStateTransition, draft.Status, StatusPendingReview)
	}
	draft.Status = StatusPendingReview
	draft.Version++
	draft.UpdatedAt = time.Now().UTC()
	return nil
}

// Approve transitions a pending-review or failed draft into APPROVED so publishing can proceed.
func (draft *ContentDraft) Approve() error {
	if draft.Status != StatusPendingReview && draft.Status != StatusFailed {
		return fmt.Errorf("%w: cannot approve draft in status %s", ErrInvalidStateTransition, draft.Status)
	}
	draft.Status = StatusApproved
	draft.FailureReason = ""
	draft.Version++
	draft.UpdatedAt = time.Now().UTC()
	return nil
}

// Reject transitions a pending-review or failed draft into REJECTED (no publishing occurs).
func (draft *ContentDraft) Reject() error {
	if draft.Status != StatusPendingReview && draft.Status != StatusFailed {
		return fmt.Errorf("%w: cannot reject draft in status %s", ErrInvalidStateTransition, draft.Status)
	}
	draft.Status = StatusRejected
	draft.Version++
	draft.UpdatedAt = time.Now().UTC()
	return nil
}

// MarkPublished records a successful external publication ID for an approved draft.
func (draft *ContentDraft) MarkPublished(externalPostID string) error {
	if draft.Status != StatusApproved {
		return fmt.Errorf("%w: cannot mark draft published from status %s", ErrInvalidStateTransition, draft.Status)
	}
	draft.Status = StatusPublished
	draft.ExternalPostID = strings.TrimSpace(externalPostID)
	draft.FailureReason = ""
	draft.Version++
	draft.UpdatedAt = time.Now().UTC()
	return nil
}

// MarkFailed records a terminal publishing failure reason for an approved draft.
func (draft *ContentDraft) MarkFailed(reason string) error {
	if draft.Status != StatusApproved {
		return fmt.Errorf("%w: cannot mark draft failed from status %s", ErrInvalidStateTransition, draft.Status)
	}
	draft.Status = StatusFailed
	draft.FailureReason = strings.TrimSpace(reason)
	draft.Version++
	draft.UpdatedAt = time.Now().UTC()
	return nil
}

// CanTransitionTo reports whether transitioning to targetStatus is permitted under the domain state machine.
func (draft *ContentDraft) CanTransitionTo(targetStatus DraftStatus) bool {
	switch targetStatus {
	case StatusCritiqued:
		return draft.Status == StatusDraft || draft.Status == StatusCritiqued
	case StatusPendingReview:
		return draft.Status == StatusDraft || draft.Status == StatusCritiqued
	case StatusApproved, StatusRejected:
		return draft.Status == StatusPendingReview || draft.Status == StatusFailed
	case StatusPublished, StatusFailed:
		return draft.Status == StatusApproved
	default:
		return false
	}
}

// DraftBatch aggregates all 4 platform drafts produced from a single CommitEvent.
type DraftBatch struct {
	ID                string                     `json:"id"`
	CommitEvent       CommitEvent                `json:"commit_event"`
	Drafts            map[Platform]*ContentDraft `json:"drafts"`
	DiscordMessageID  string                     `json:"discord_message_id,omitempty"`
	TelegramMessageID string                     `json:"telegram_message_id,omitempty"`
	CreatedAt         time.Time                  `json:"created_at"`
	UpdatedAt         time.Time                  `json:"updated_at"`
}

// NewDraftBatch validates commitEvent and constructs a new DraftBatch aggregate root.
func NewDraftBatch(batchID string, commitEvent CommitEvent) (*DraftBatch, error) {
	if strings.TrimSpace(batchID) == "" {
		return nil, fmt.Errorf("%w: batch_id is required", ErrValidationFailed)
	}
	if err := commitEvent.Validate(); err != nil {
		return nil, err
	}
	now := time.Now().UTC()
	return &DraftBatch{
		ID:          strings.TrimSpace(batchID),
		CommitEvent: commitEvent,
		Drafts:      make(map[Platform]*ContentDraft),
		CreatedAt:   now,
		UpdatedAt:   now,
	}, nil
}
